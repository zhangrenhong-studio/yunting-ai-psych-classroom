/* ==========================================================================
   云听 AI 智慧心理教室 · 兜底话术池（引擎资产）
   --------------------------------------------------------------------------
   为什么兜底话术必须锁在引擎里，而不是让课程包自由写？

   因为「不匹配时说什么」正是最容易滑向判断的位置。作者写具体话题时是清醒的，
   但写到兜底时，很容易顺手写出「你看起来有点焦虑」这种话——它不是恶意的，
   它只是体贴，而体贴正是越界的开始。把兜底锁进引擎，作者就没有机会写它。

   池子里每一句话只允许做三件事：
     · 反映 —— 用学生自己的词把话还回去
     · 许可 —— 允许他停在这里、允许说不清
     · 邀请 —— 请他再说一点，或往前一步

   池子里禁止出现：
     · 疾病 / 程度 / 分级词（焦虑、抑郁、自卑、内向、社恐、障碍、症、严重、风险、等级、评分、测验、诊断）
     · 把学生变成形容词（"你是一个……的人" / "你很……" / "你有点……"）
     · 猜测没说出口的感受（"你是不是觉得……" / "听起来你很……"）
     · 建议与评判（"你应该……" / "其实你可以……" / "这样想是不对的" / "别想太多"）
   ========================================================================== */

(function (global) {
  'use strict';

  var POOLS = {

    /* 学生写了东西，但没命中任何分支，或命中的分不够。
       做法：先收下（引用原话），再邀请，且明确允许停在这里。 */
    reflect: [
      '我听见了。你写的这几个字，我先收下。',
      '谢谢你愿意写下来。你可以多说一点，也可以就停在这里。',
      '我在听。你说的这些是你自己的话，我不会替你解释。',
      '我听到了。想说的部分，说多少都可以。',
      '你说的我记下了。要不要再往旁边想一想，都可以。'
    ],

    /* 命中并列：我们没听懂，那就承认没听懂，而不是猜。 */
    widen: [
      '你提到的好像是好几件事。你愿意挑其中一件，再说一点点吗？',
      '我不太确定自己有没有听对。你能换一种说法吗？或者只说此刻最想说的那一点点。',
      '这里可以慢一点。你想从哪一部分说起都可以。',
      '你写的这些，我想更靠近一点。哪一句是你最想让我听见的？'
    ],

    /* 学生选择跳过 / 什么都没写。
       跳过永远只被回应为"可以"——绝不挽留。
       挽留会把"可以不说"悄悄变成"其实最好说"。 */
    skip: [
      '没关系，我们先往下走。',
      '好。不说也可以。',
      '嗯，那就先放在这里。',
      '我明白。我们接着往下。'
    ],

    /* 学生表达了明确的情绪强度，但仍不做任何判断——只把节奏放慢。 */
    steady: [
      '我在。你不用急着把它说清楚。',
      '谢谢你告诉我这些。我们先停在这里也可以。',
      '你说的这些，我收下了。想停就停。'
    ]
  };

  /* --- 课程包里的分支回复也会被这道检查扫一遍 --- */
  var FORBIDDEN = [
    // 疾病 / 程度 / 分级
    '焦虑', '抑郁', '自卑', '内向', '外向', '社恐', '孤僻', '障碍', '症',
    '严重', '风险', '等级', '评分', '测验', '诊断', '评估', '心理问题', '不健康',
    // 把学生变成形容词
    '你是一个', '你是个', '你很', '你有点', '你比较', '你太', '你总是', '你从来',
    // 猜测没说出口的感受
    '你是不是觉得', '听起来你很', '我猜你', '你肯定', '你一定',
    // 建议与评判
    '你应该', '你不该', '其实你可以', '你要学会', '这样想是不对的', '别想太多',
    '想开点', '这很正常', '很多人都这样'
  ];

  /** 扫一段文本，返回命中的禁词数组（空数组表示通过）。 */
  function check(text) {
    var hits = [];
    if (!text) { return hits; }
    var s = String(text);
    for (var i = 0; i < FORBIDDEN.length; i++) {
      if (s.indexOf(FORBIDDEN[i]) !== -1) { hits.push(FORBIDDEN[i]); }
    }
    return hits;
  }

  /** 从某个池子里取一条，避免连续重复（就一个学生的会话而言够用了）。 */
  var lastPick = {};

  function draw(poolKey) {
    var pool = POOLS[poolKey] || POOLS.reflect;
    if (pool.length === 1) { return pool[0]; }
    var i;
    do {
      i = Math.floor(Math.random() * pool.length);
    } while (pool[i] === lastPick[poolKey] && pool.length > 1);
    lastPick[poolKey] = pool[i];
    return pool[i];
  }

  global.YTFallback = {
    pools: POOLS,
    forbidden: FORBIDDEN,
    check: check,
    draw: draw
  };
})(window);
